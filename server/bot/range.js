//
// 从行动序列反推对手范围的启发式。
//
// 两个用途：
//
//   1. **不带 LLM 的那条路要用**。规则策略（policy.js）判断「面对下注该不该跟」
//      靠的是胜率和底池赔率比大小。以前那个胜率按「对手随机两张牌」算，
//      系统性偏乐观，于是规则人机会做一堆亏钱的跟注。现在 BotDriver 会先用
//      这个函数推一个范围出来，再按那个范围算胜率。
//
//   2. **评测的仪器**。「范围建模到底有没有用」这个问题不该由模型来回答——
//      那样测出来的是模型判断力和范围建模价值的乘积。用这个确定性的笨办法
//      做纯消融，唯一变量就只剩「胜率按什么假设算」。
//
// 它故意做得很笨，只看一件事：**对手主动进攻了几次**。每次进攻把范围乘以一个
// 收缩系数，街数越靠后额外再收一点。没有牌面结构分析，没有位置修正，
// 没有对手画像——那些是 agent 版里模型该干的活（见 agent/tools.js）。
//
// 已知短板，用之前必须知道：**翻牌前没人加注时它推断不出任何东西**（返回 1，
// 等于没做范围建模），而翻牌前占了全部「用得上胜率」的决策的 77%。
// 数字见 README 的评测一节。

// 下面这几个常数是**用数据标定出来的**，不是拍脑袋。
//
// 标定办法见 eval/harness.js 的 runCalibration：评测里我们拿着引擎的全信息，
// 于是可以直接问「启发式说对手范围是前 X%，那些人手里的牌实际排第几百分位」。
// 第一版（首次 0.45、每次再乘 0.45、下限 0.05）的结果是：
//
//   假设前 5%  → 对手实际前 20%   紧了 4 倍
//   假设前 10% → 对手实际前 20%   紧了 2 倍
//   假设前 45% → 对手实际前 20%   反而松了 2.2 倍
//
// 两个方向相反的错误，指向同一个结论：**第一次进攻的信息量最大，之后每次
// 进攻补充的信息少得多**，而原来那个连乘模型对两者一视同仁，于是复合得太狠。
// 「有人连开三条街 = 他只玩前 5% 的牌」在任何玩家群体里都荒谬——真人会诈唬。
// 范围推得过紧的直接后果是人机弃掉本该跟的牌，在 bb/100 上就是净亏损。
//
// ---- 第二次标定（换了排序之后必须重来）----
//
// 上面那组数是对着**纯胜率排序**标的。equity.js 后来把排序换成了
// 「可玩性档位 + 胜率」（见 data/ranges.js），"前 X%" 指的已经是另一批牌，
// 于是常数全部作废，必须重标。换序之后同样三个种子各 700 副：
//
//   假设前 10% → 对手实际前 10%   1×      ← 换序自己就修好了
//   假设前 20% → 对手实际前 20%   1×      ← 换序自己就修好了
//   假设前 35% → 对手实际前 10%   0.3×    ← 只剩这一个，而且三个种子一致
//
// 换句话说：换排序把「推得过紧」那一类错误直接消掉了（原来最紧的桶紧了 4 倍），
// 剩下的唯一系统误差是**单次加注推得过松**——说前 35%，人家其实是前 10%。
//
// 但这里**故意不追平**。标定用的是规则人机自己的群体：它的开火阈值是一个
// 固定的 handStrength 门槛，翻牌前从不诈唬，所以「有人加注」在它身上等价于
// 「他真有牌」。真人和 LLM 都不是这样——他们开池宽得多，也会偷盲。
// 照着 0.10 去拟合等于把一个不会诈唬的对手的性质焊死进代码。
// 取 0.22 是有意的折中：把三倍误差压到两倍出头，剩下的余量留给会诈唬的人。
//
// 下限试过降到 0.06，想给多街进攻留出区分度——**实测退回来了**：
// 前 5% 那个桶立刻变成紧了 2~4 倍，正是 0.12 当初要挡的那类错误。
// 换序修好的是「一次加注」附近，不是最紧的那一端；连开三条街依然不能
// 推成「只玩前 6%」。所以下限保持 0.12，代价是三条街以上会被夹平。
//
// 定下来这组（0.22 / 0.12）之后，三个种子的最大偏差从 3.3 倍降到 2 倍：
//
//   假设前 10% → 实际前 10% / 前 20% / 前 10%    1× / 2× / 1×
//   假设前 20% → 实际前 10%（三个种子一致）      0.5×
//   假设前 100% → 实际前 50%（三个种子一致）     0.5×  ← 这个是对的，随机牌中位就是 50%

/** 第一次看到对手主动开火时，范围收到这个比例。信息量最大的一步。 */
const FIRST_SHRINK = 0.22;
/** 之后每多一次进攻再乘这个。边际信息量小得多，所以温和很多。 */
const EXTRA_SHRINK = 0.8;
/** 每多走一条街额外乘这个（跟到后面的人手里通常有点东西） */
const STREET_SHRINK = 0.9;
/**
 * 范围下限。够低才容得下多街进攻的区分度，又不至于让人机相信
 * 「他连开三条街 = 只玩前 2%」这种在任何群体里都不成立的结论。
 */
const FLOOR = 0.12;

const STREET_ORDER = ['preflop', 'flop', 'turn', 'river'];

/**
 * 从本手的行动序列推断「对手大概只玩前百分之几的起手牌」。
 *
 * @param {object} args
 * @param {Array<{street:string, acts:Array<{seat:number,type:string,amount:number}>}>} args.history
 *        Room#buildStateFor 快照里的 table.history（不含盲注，盲注是 blind 事件）
 * @param {number} args.mySeat  自己的座位，自己的动作不算数
 * @returns {number} 0.05 ~ 1 之间。1 表示「没有任何信息，当随机两张牌」
 */
export function inferOpponentRange({ history, mySeat }) {
  if (!Array.isArray(history) || history.length === 0) return 1;

  let range = 1;
  let streets = 0;
  let attacks = 0;

  for (const st of history) {
    if (!st || !Array.isArray(st.acts)) continue;
    if (!STREET_ORDER.includes(st.street)) continue;
    streets++;

    for (const a of st.acts) {
      if (!a || a.seat === mySeat) continue;          // 自己的动作不提供对手信息
      if (a.type === 'bet' || a.type === 'raise' || a.type === 'allin') {
        attacks++;
        // 第一次进攻收得多，之后每次收得少 —— 边际信息量是递减的
        range *= attacks === 1 ? FIRST_SHRINK : EXTRA_SHRINK;
      }
    }
  }

  // 第一条街不额外收缩（大家都在场），之后每多一条街收一点
  if (streets > 1) range *= STREET_SHRINK ** (streets - 1);

  return Math.max(FLOOR, Math.min(1, range));
}

export default inferOpponentRange;
